-- L1 Support Copilot schema, H2 dialect (dev profile). Keep in sync with schema-postgresql.sql.
CREATE TABLE IF NOT EXISTS users (
    id         VARCHAR(20)  PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(150) NOT NULL,
    age        INTEGER      NOT NULL,
    avatar_url VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS orders (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            VARCHAR(20)  NOT NULL REFERENCES users(id),
    description        VARCHAR(255) NOT NULL,
    status             VARCHAR(20)  NOT NULL,
    order_date         DATE         NOT NULL,
    estimated_delivery DATE,
    tracking_carrier   VARCHAR(50),
    image_url          VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS tickets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     VARCHAR(20)   NOT NULL REFERENCES users(id),
    order_id    BIGINT        REFERENCES orders(id),
    subject     VARCHAR(200)  NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status      VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMP     NOT NULL
);

-- Agent turn log (golden-set raw material): no FK to users and not part of the seed reset.
CREATE TABLE IF NOT EXISTS turn_log (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts              TIMESTAMP     NOT NULL,
    conversation_id VARCHAR(100),
    user_id         VARCHAR(20),
    message         VARCHAR(4000),
    intent          VARCHAR(20),
    awaiting        VARCHAR(20),
    order_id        BIGINT,
    orders_shown    INTEGER,
    tickets_created INTEGER,
    resolved        BOOLEAN,
    reply           VARCHAR(4000)
);
